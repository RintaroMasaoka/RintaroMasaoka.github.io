import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { numberEquations } from '../src/utils/note-equations.mjs';
const r=createRequire(import.meta.url),k=createRequire(r.resolve('rehype-katex'))('katex');
const eq=(key,body='x=1')=>k.renderToString(`${body}\\tag{${key}}`,{displayMode:true});
const first=eq('first'),second=eq('second');
const readNumbers=html=>[...html.matchAll(/data-equation-number="(\d+)"/g)].map(m=>m[1]);
const before=numberEquations(`${first}${second}<p>式 (@second)、式 (@first)。</p>`);
assert.deepEqual(readNumbers(before),['1','2']);assert.match(before,/<p>式 \(2\)、式 \(1\)。<\/p>/);
const inserted=numberEquations(`${eq('inserted')}${first}${second}<p>式 (@second)、式 (@first)。</p>`);
assert.deepEqual(readNumbers(inserted),['1','2','3']);assert.match(inserted,/<p>式 \(3\)、式 \(2\)。<\/p>/);
assert.match(numberEquations(`${eq('2')}${eq('named')}<p>(@named)</p>`), /<p>\(2\)<\/p>/);
const reordered=numberEquations(`${second}${first}<p>式 (@first)。</p>`);
assert.match(reordered,/<p>式 \(2\)。<\/p>/);assert.match(reordered,/id="eq-first"/);
assert.throws(()=>numberEquations(first+first),/Duplicate note equation key/);
assert.throws(()=>numberEquations('<p>式 (@missing)。</p>'),/Unknown note equation reference/);
const inline=k.renderToString('f(1)=0');const preserved=numberEquations(`${eq('1')}${inline}<a href="https://example.org">source (1)</a><code>(@missing)</code>`);
assert.ok(preserved.includes(inline));assert.match(preserved,/>source \(1\)<\/a>/);assert.match(preserved,/<code>\(@missing\)<\/code>/);
assert.deepEqual(readNumbers(numberEquations(k.renderToString('a=b',{displayMode:true}))),[]);
console.log('PASS: automatic numbers, insertion, reordering, references, stable anchors, duplicate/unknown failures, unnumbered calculations, inline math and external citations.');
